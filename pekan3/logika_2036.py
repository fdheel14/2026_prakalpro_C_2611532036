a1_2036 = int(input("Input nilai a1: "))
a2_2036 = int(input("Input nilai a2: "))

# Operator Logika
hasil_2036 = a1_2036 and a2_2036
print("a1 and a2 =", hasil_2036)

#Disjungsi: bernilai True jika salah satunya True
hasil_2036 = a1_2036 or a2_2036
print("\nDisjungsi (OR)")
print("a1 or a2 =", hasil_2036)

#Negasi A1: membalik nilai A1
hasil_2036 = not a1_2036
print("\nNegasi A1 (NOT)")
print("not a1 =", hasil_2036)

#Negasi A2: Membalik nilai A2
hasil_2036 = not a2_2036
print("\nNegasi A2 (NOT)")
print("not a2 =", hasil_2036)

#XOR: bernilai True jika kedua nilai berbeda
hasil_2036 = a1_2036 ^ a2_2036
